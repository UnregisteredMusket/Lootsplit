import assert from "node:assert/strict";
import "fake-indexeddb/auto";
const values=new Map();
const storage={getItem:key=>values.get(key)??null,setItem:(key,value)=>values.set(key,String(value)),removeItem:key=>values.delete(key)};
const victim={id:"victim",name:"Deleting",db:"quire-delete-victim"};
const survivor={id:"survivor",name:"Survivor",db:"quire-delete-survivor"};
storage.setItem("quire.campaigns.v1",JSON.stringify([victim,survivor]));
storage.setItem("quire.campaign.v1","victim");
storage.setItem("quire.owner.survivor","fixture-owner");
storage.setItem("lootsplit.verified-account","fixture-owner");
storage.setItem("quire.deletion.v1",JSON.stringify({target:victim,next:{campaigns:[survivor],activeId:"survivor"}}));
Object.assign(globalThis,{localStorage:storage,sessionStorage:storage,window:{localStorage:storage,location:{search:"",hash:""}}});
const open=indexedDB.open(victim.db);
const blocker=await new Promise((resolve,reject)=>{open.onsuccess=()=>resolve(open.result);open.onerror=()=>reject(open.error);});
blocker.onversionchange=()=>{};
const {getCampaigns,createCampaign,renameCampaign,switchCampaign,deleteCampaign,selectAccountCampaign,subscribeCampaigns}=await import("../src/lib/quire/campaigns.ts");
getCampaigns();
assert.throws(()=>createCampaign("Blocked"),/deletion is still finishing/);
assert.throws(()=>renameCampaign("survivor","Blocked"),/deletion is still finishing/);
assert.throws(()=>switchCampaign("survivor"),/deletion is still finishing/);
await assert.rejects(deleteCampaign("survivor"),/deletion is still finishing/);
assert.throws(()=>selectAccountCampaign("account-blocked","Blocked",{role:"dm",purseIds:[],shopIds:[]}),/deletion is still finishing/);
// Simulate a newer registry committed by an older still-open tab during the blocked delete.
const newer={id:"newer",name:"Newer tab campaign",db:"quire-newer"};
storage.setItem("quire.campaigns.v1",JSON.stringify([victim,{...survivor,name:"Renamed in another tab"},newer]));
storage.setItem("quire.campaign.v1","newer");
const recovered=new Promise(resolve=>{const off=subscribeCampaigns(()=>{if(storage.getItem("quire.deletion.v1")===null){off();resolve();}});});
blocker.close();await recovered;
assert.deepEqual(getCampaigns().campaigns.map(c=>c.id),["survivor","newer"]);
assert.equal(getCampaigns().campaigns[0].name,"Renamed in another tab");
assert.equal(getCampaigns().activeId,"newer");
createCampaign("After recovery");
assert.equal(getCampaigns().campaigns.length,3);
const currentTab=getCampaigns().activeId;
storage.setItem("quire.campaign.v1","survivor");
renameCampaign("survivor","Another tab metadata retained");
assert.equal(getCampaigns().activeId,currentTab,"Registry reconciliation must not silently adopt another tab's seat");
assert.equal(storage.getItem("quire.campaign.v1"),currentTab);
console.log("Recovered deletion preserves newer tab registry changes and blocks overlapping mutations.");
